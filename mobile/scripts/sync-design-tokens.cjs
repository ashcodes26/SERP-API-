// JSON is the source for native styles and generated web variables. No dependencies.
const fs = require('node:fs');
const path = require('node:path');
const tokens = require('../src/constants/design-tokens.json');
const target = path.join(__dirname, '../src/constants/variables.css');
const declarations = [];
for (const [name, value] of Object.entries(tokens.colors)) declarations.push(`  --color-${name}: ${value};`);
for (const group of ['spacing', 'radii', 'sizes', 'breakpoints', 'layout']) {
  for (const [name, value] of Object.entries(tokens[group])) declarations.push(`  --${group}-${name}: ${value}px;`);
}
declarations.push('  --spacing-unit: var(--spacing-one);', '  --page-max-width: var(--layout-workspace);');
const output = `/* Generated by scripts/sync-design-tokens.cjs; edit design-tokens.json. */\n:root {\n${declarations.join('\n')}\n}\n`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) {
    console.error('Design variables are stale. Run node scripts/sync-design-tokens.cjs.');
    process.exitCode = 1;
  } else console.log('Design variables match the canonical tokens.');
} else fs.writeFileSync(target, output);
